test('notification cutover is explicit and verifies the typed runtime before changing the setting', () => {
  const activation = source('server/utils/connectorRuntimeActivation.ts')
  const route = source('server/api/v1/console/connector-runtime/notification-activation.post.ts')
  const settings = source('server/utils/systemParameters.ts')
  const foundationNotify = source('../foundation/server/utils/notify.ts')
  const integrations = source('server/utils/integrations.ts')
  const migrationScript = source('../connector-runtime/deploy/migrate-notification-runtime.sh')
  assert.match(route, /requireSystemSettingsAccess\(event, 'admin'\)[\s\S]*readBody/)
  assert.match(activation, /hzy-connector-runtime/)
  assert.match(activation, /hzy\.connector-capabilities\.v1/)
  assert.match(activation, /arbitraryHttpProxy !== false/)
  assert.match(activation, /connector-runtime:notifications:send/)
  assert.match(activation, /updateManagedSettingValue\([\s\S]*connector\.notificationsEnabled[\s\S]*value: true/)
  assert.doesNotMatch(activation, /\bupdateSettingValue\b/)
  assert.match(route, /getHeader\(event, 'idempotency-key'\)/)
  assert.match(settings, /getConsoleSettingValues/)
  assert.match(settings, /updateConsoleManagedSettingValue/)
  assert.match(settings, /expectedRevision: current\.revision/)
  assert.doesNotMatch(settings, /server\/utils\/db|queryRow|queryRows|execute|withTransaction/)
  assert.match(foundationNotify, /connector\.notificationsEnabled/)
  assert.match(foundationNotify, /audience: 'connector-runtime'/)
  assert.match(foundationNotify, /scope: 'connector-runtime:notifications:send'/)
  assert.match(integrations, /resolveNotificationDeliveryTarget/)
  assert.match(integrations, /deliveryMode: 'connector-runtime'/)
  assert.match(migrationScript, /systemctl stop "\$SOURCE_SERVICE\.service"/)
  assert.match(migrationScript, /install -m 0600 "\$source_db" "\$target_db"/)
  assert.match(migrationScript, /"\$TARGET_BINARY" -check-store/)
  assert.match(migrationScript, /arbitraryHttpProxy/)
  assert.match(migrationScript, /Connector cutover failed; Notification Runtime was restored/)
})
