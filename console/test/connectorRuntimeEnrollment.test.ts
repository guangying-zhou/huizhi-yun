import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import { test } from 'node:test'

const source = (path: string) => readFileSync(new URL(`../${path}`, import.meta.url), 'utf8')

test('connector runtime install command contains only a short-lived enrollment code', () => {
  const content = source('server/utils/connectorRuntimeEnrollment.ts')
  const runtime = source('../data-runtime/internal/apps/console/connector_runtime.go')
  assert.match(runtime, /connectorRuntimeEnrollmentTTL = 15 \* time\.Minute/)
  assert.match(runtime, /"hzy_cre_" \+ base64\.RawURLEncoding/)
  assert.match(runtime, /enrollment_token_sha256/)
  assert.match(runtime, /sha256\.Sum256\(\[\]byte\(code\)\)/)
  assert.match(content, /HZY_CONNECTOR_RUNTIME_ENROLLMENT_CODE=/)
  assert.match(content, /HZY_CONNECTOR_RUNTIME_RELEASE_PUBLIC_KEY_PEM_BASE64/)
  assert.match(content, /HZY_CONNECTOR_RUNTIME_DATA_RUNTIME_URL=/)
  assert.match(content, /resolveDataRuntimeParameters\(event\)/)
  assert.match(content, /Data Runtime 地址未配置或不安全/)
  assert.match(content, /openssl pkeyutl -verify -rawin/)
  assert.doesNotMatch(content.slice(content.indexOf('function installCommand'), content.indexOf('export async function getConnectorRuntimeMetadata')), /CLIENT_SECRET|clientSecret/)
  const installer = source('../connector-runtime/deploy/install.sh')
  const packager = source('../connector-runtime/scripts/package-release.sh')
  assert.match(installer, /verify_signature "\$manifest" "\$manifest_signature"/)
  assert.match(installer, /verify_signature "\$archive" "\$archive_signature"/)
  assert.match(packager, /HZY_CONNECTOR_RUNTIME_RELEASE_SIGNING_KEY_FILE/)
  assert.match(packager, /pkeyutl -sign -rawin/)
})

test('enrollment is binding-scoped, single use and encrypts the issued credential', () => {
  const bff = source('server/utils/connectorRuntimeEnrollment.ts')
  const runtime = source('../data-runtime/internal/apps/console/connector_runtime.go')
  const foundation = source('../foundation/server/utils/consoleTenantRuntimeClient.ts')
  assert.doesNotMatch(bff, /server\/utils\/db|queryRow|queryRows|execute|withTransaction/)
  assert.match(foundation, /\/v1\/console\/connector-runtime\/enroll/)
  assert.match(runtime, /LIMIT 1 FOR UPDATE/)
  assert.match(runtime, /status != "issued"/)
  assert.match(runtime, /tenantCode != a\.tenant \|\| boundDeployment != deploymentCode/)
  assert.match(runtime, /status='redeemed'.*WHERE enrollment_id=\? AND status='issued'/s)
  assert.match(runtime, /publicKey\.N\.BitLen\(\) < 3072/)
  assert.match(runtime, /rsa\.EncryptOAEP/)
  assert.match(runtime, /sha256\.New\(\)/)
  assert.match(runtime, /hzy-connector-runtime-enrollment\.v1/)
  assert.match(runtime, /"integrationCodes": \[\]string\{"wecom\.default", "dingtalk\.default", "dingtalk\.identity"\}/)
  assert.match(runtime, /\{"credential_vault", "resolve"/)
  assert.match(runtime, /\{"console:connector-runtime", "heartbeat"/)
  assert.match(runtime, /resource_code='connector_runtime'[\s\S]*action='heartbeat'[\s\S]*status='active'/)
  assert.match(runtime, /backend_secret_ref,content_hash,encryption_scheme[\s\S]*'hash-only'[\s\S]*'sha256-only'/)
  assert.doesNotMatch(runtime, /ciphertext_blob[\s\S]*clientSecret/)
})

