  assert.match(page, /requestKey: globalThis\.crypto\.randomUUID\(\)/)
  assert.match(page, /if \(!response\.data\.replayVerified\)/)
  assert.match(page, /幂等重放已验证/)
  assert.match(page, /!canEditIntegrations \|\| !selectedIntegration/)
