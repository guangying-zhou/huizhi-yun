  assert.match(route, /replayVerified: true/)
  assert.match(block, /row\.integrationType !== provider/)
  assert.match(block, /provider === 'dingtalk' && target\.deliveryMode !== 'connector-runtime'/)
  assert.match(block, /channel: provider/)
  assert.match(block, /`console:connector-runtime:dingtalk-test:\$\{requestKey\}`/)
