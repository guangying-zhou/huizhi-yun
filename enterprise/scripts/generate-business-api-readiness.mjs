#!/usr/bin/env node
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { deriveBusinessApiSurface } from '../composition/business-api-surface.mjs'

export const generatedPath = fileURLToPath(new URL('../composition/business-api-routes.generated.mjs', import.meta.url))

export function renderBusinessApiRoutes(surface = deriveBusinessApiSurface()) {
  const prefixes = surface.prefixes.map(prefix => `'${prefix}'`).join(', ')
  const routes = surface.routes.map(({ method, route }) => `  ['${method}', '${route}']`).join(',\n')
  return `// GENERATED by scripts/generate-business-api-readiness.mjs — do not edit by hand.
// Run \`pnpm --dir enterprise generate:api-readiness\` after adding or removing a
// business API route. business-api-readiness.test.mjs fails when this drifts.
export const businessApiPrefixes = Object.freeze([${prefixes}])

export const businessApiRoutes = Object.freeze([
${routes}
].map(entry => Object.freeze(entry)))
`
}

if (import.meta.url === `file://${process.argv[1]}`) {
  writeFileSync(generatedPath, renderBusinessApiRoutes())
  console.log(`Wrote ${generatedPath}`)
}
