CREATE TABLE finance_invoice (
    id                      BIGINT UNSIGNED PRIMARY KEY AUTO_INCREMENT,
    code                    VARCHAR(64)  NOT NULL COMMENT 'IV-xxxxxx；唯一正式发票事实源',
    invoice_no              VARCHAR(80)  DEFAULT NULL COMMENT '税务发票号码',
    invoice_request_id      BIGINT UNSIGNED DEFAULT NULL,
    customer_code           VARCHAR(64)  DEFAULT NULL,
    customer_name           VARCHAR(200) DEFAULT NULL,
    contract_code           VARCHAR(64)  DEFAULT NULL,
    project_code            VARCHAR(64)  DEFAULT NULL,
    billing_schedule_code   VARCHAR(64)  DEFAULT NULL,
    invoice_type            VARCHAR(30)  DEFAULT NULL,
    invoice_medium          VARCHAR(20)  NOT NULL DEFAULT 'electronic',
    invoice_item            VARCHAR(500) DEFAULT NULL,
    invoice_amount          DECIMAL(18,2) NOT NULL COMMENT '价税合计（正数；红冲由状态 + reversal_of_invoice_id 表达）',
    currency_code           CHAR(3) NOT NULL DEFAULT 'CNY',
    tax_rate                DECIMAL(5,2) DEFAULT NULL,
    tax_amount              DECIMAL(18,2) DEFAULT NULL,
    amount_tax_exclusive    DECIMAL(18,2) DEFAULT NULL,
    invoice_date            DATE DEFAULT NULL,
    status                  VARCHAR(30)  NOT NULL DEFAULT 'issued' COMMENT 'draft/issued/red_reversed/canceled',
    reconciled_amount       DECIMAL(18,2) NOT NULL DEFAULT 0.00 COMMENT '有效核销分配累计（核销事务维护）',
    unreconciled_amount     DECIMAL(18,2) GENERATED ALWAYS AS (GREATEST(invoice_amount - reconciled_amount, 0)) STORED,
    taxpayer_name           VARCHAR(200) DEFAULT NULL,
    taxpayer_no             VARCHAR(50)  DEFAULT NULL,
    receiver_name           VARCHAR(200) DEFAULT NULL,
    invoice_file_key        VARCHAR(500) DEFAULT NULL COMMENT 'OSS key（原 invoice_file_url；不存签名 URL）',
    invoice_file_name       VARCHAR(255) DEFAULT NULL,
    invoice_file_mime_type  VARCHAR(100) DEFAULT NULL,
    invoice_file_size       BIGINT UNSIGNED DEFAULT NULL,
    reversal_of_invoice_id  BIGINT UNSIGNED DEFAULT NULL COMMENT '红字发票指向被冲蓝票',
    reversed_at             DATETIME(3) DEFAULT NULL,
    reversed_by             VARCHAR(64)  DEFAULT NULL,
    reverse_reason          VARCHAR(500) DEFAULT NULL,
    issued_by               VARCHAR(64)  DEFAULT NULL,
    remark                  VARCHAR(500) DEFAULT NULL,
    row_version             INT UNSIGNED NOT NULL DEFAULT 1,
    created_by              VARCHAR(64) DEFAULT NULL,
    updated_by              VARCHAR(64) DEFAULT NULL,
    created_at              DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at              DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    deleted_at              DATETIME(3) DEFAULT NULL,
    UNIQUE KEY uk_finance_invoice_code (code),
    UNIQUE KEY uk_finance_invoice_no (invoice_no),
    KEY idx_finance_invoice_request (invoice_request_id),
    KEY idx_finance_invoice_contract (contract_code, status),
    KEY idx_finance_invoice_customer (customer_code),
    KEY idx_finance_invoice_project (project_code),
    KEY idx_finance_invoice_schedule (billing_schedule_code),
    KEY idx_finance_invoice_date (invoice_date),
    KEY idx_finance_invoice_status (status, deleted_at),
    KEY idx_finance_invoice_reversal (reversal_of_invoice_id),
    CONSTRAINT fk_finance_invoice_request FOREIGN KEY (invoice_request_id) REFERENCES finance_invoice_request(id),
    CONSTRAINT fk_finance_invoice_reversal FOREIGN KEY (reversal_of_invoice_id) REFERENCES finance_invoice(id),
    CONSTRAINT ck_finance_invoice_amounts CHECK (invoice_amount >= 0 AND reconciled_amount >= 0 AND reconciled_amount <= invoice_amount)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='正式发票（唯一事实源；Altoc 只读）';

