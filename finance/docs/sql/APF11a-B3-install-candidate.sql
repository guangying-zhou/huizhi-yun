CREATE TABLE finance_reconciliation (
    id                      BIGINT UNSIGNED PRIMARY KEY AUTO_INCREMENT,
    code                    VARCHAR(64)  NOT NULL COMMENT 'RL-xxxxxx；核销分配行（一笔到账 → 一个目标 → 一个金额）',
    receipt_id              BIGINT UNSIGNED NOT NULL,
    target_type             VARCHAR(30)  NOT NULL COMMENT 'invoice/billing_schedule/contract/advance/unclassified/manual',
    invoice_id              BIGINT UNSIGNED DEFAULT NULL,
    customer_code           VARCHAR(64)  DEFAULT NULL,
    contract_code           VARCHAR(64)  DEFAULT NULL,
    project_code            VARCHAR(64)  DEFAULT NULL,
    billing_schedule_code   VARCHAR(64)  DEFAULT NULL COMMENT '目标结算计划（Altoc 共享事务回写键）',
    reconciled_amount       DECIMAL(18,2) NOT NULL,
    currency_code           CHAR(3) NOT NULL DEFAULT 'CNY',
    reconciled_at           DATETIME(3) NOT NULL,
    status                  VARCHAR(30)  NOT NULL DEFAULT 'active' COMMENT 'active/reversed',
    reversed_at             DATETIME(3) DEFAULT NULL,
    reversed_by             VARCHAR(64)  DEFAULT NULL,
    reverse_reason          VARCHAR(500) DEFAULT NULL,
    idempotency_key         VARCHAR(191) NOT NULL COMMENT '创建幂等键：Idempotency-Key 或 receipt_code+target+amount 派生',
    reconciled_by           VARCHAR(64)  DEFAULT NULL COMMENT '核销人（D-02 若采用则 ≠ receipt.confirmed_by）',
    note                    VARCHAR(500) DEFAULT NULL,
    row_version             INT UNSIGNED NOT NULL DEFAULT 1,
    created_by              VARCHAR(64) DEFAULT NULL,
    created_at              DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at              DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    UNIQUE KEY uk_finance_reconciliation_code (code),
    UNIQUE KEY uk_finance_reconciliation_idempotency (idempotency_key),
    KEY idx_finance_reconciliation_receipt (receipt_id, status),
    KEY idx_finance_reconciliation_invoice (invoice_id, status),
    KEY idx_finance_reconciliation_contract (contract_code),
    KEY idx_finance_reconciliation_schedule (billing_schedule_code, status),
    KEY idx_finance_reconciliation_project (project_code),
    KEY idx_finance_reconciliation_at (reconciled_at),
    CONSTRAINT fk_finance_reconciliation_receipt FOREIGN KEY (receipt_id) REFERENCES finance_receipt(id),
    CONSTRAINT fk_finance_reconciliation_invoice FOREIGN KEY (invoice_id) REFERENCES finance_invoice(id),
    CONSTRAINT ck_finance_reconciliation_amount CHECK (reconciled_amount > 0),
    CONSTRAINT ck_finance_reconciliation_reversal CHECK (
      (status = 'active' AND reversed_at IS NULL AND reversed_by IS NULL)
      OR (status = 'reversed' AND reversed_at IS NOT NULL AND reversed_by IS NOT NULL))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='收款核销分配（撤销为原地 reversed，不删除；汇总列由同事务重算）';

