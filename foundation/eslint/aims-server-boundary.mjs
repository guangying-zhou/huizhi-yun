// Baseline overrides only relax helper imports, never the internal boundary.
export function aimsImportBoundary(allowExistingHelpers = false) {
  const patterns = [{
    group: ['**/aims/layer/server/internal/**', '**/aims/layer/server/internal'],
    message: 'External modules must use aims/layer/server/index, never internal cores.'
  }]
  if (!allowExistingHelpers) patterns.push({
    group: aimsServiceHelpers.flatMap(name => [`**/aims/server/utils/${name}`, `**/aims/server/utils/${name}.*`]),
    message: 'New code must use owning typed entries, not Aims service identity/token/Service API helpers.'
  })
  return ['error', { patterns }]
}
