function shouldCallTenantRuntime(config: Record<string, unknown>, appCode: string, endpoint: string) {
  const mode = dataAccessMode(config, appCode)
  if (mode === 'direct-db') return false
  if (mode === 'tenant-runtime' || mode === 'fallback') return Boolean(endpoint)
  return isTenantRuntimeProfile(resolveDeploymentProfile(config)) && Boolean(endpoint)
}

function appendQuery(url: URL, query: Record<string, unknown>) {
  for (const [key, value] of Object.entries(query)) {
    if (value === undefined || value === null) continue
    if (Array.isArray(value)) {
      for (const item of value) {
        if (item !== undefined && item !== null) url.searchParams.append(key, String(item))
      }
      continue
    }
    url.searchParams.set(key, String(value))
  }
}

function normalizeMethod(value: unknown): TenantRuntimeMethod {
  const method = String(value || 'GET').toUpperCase()
  if (method === 'POST' || method === 'PATCH' || method === 'PUT' || method === 'DELETE') return method
  return 'GET'
}

export function tenantRuntimeTokenScope(audience: string, scope: string): string {
  const normalizedAudience = stringValue(audience)
  const normalizedScope = stringValue(scope)
  if (!normalizedAudience || !normalizedScope) return normalizedScope
  const scopes = normalizedScope.split(/\s+/).filter(Boolean)
  if (scopes.length > 1) {
    return scopes.map(item => tenantRuntimeTokenScope(normalizedAudience, item)).join(' ')
  }
  if (normalizedScope.startsWith('console:')) return normalizedScope
  if (normalizedScope.startsWith(`${normalizedAudience}:`)) return normalizedScope

  if (normalizedScope.includes(':')) {
    return `${normalizedAudience}:${normalizedScope}`
  }

  const [appCode, action] = normalizedScope.split(/\.(.+)/).filter(Boolean)
  if (!appCode || !action) return normalizedScope

  return `${normalizedAudience}:${appCode}:${action}`
}

async function resolveBearerToken(event: H3Event, options: TenantRuntimeCallOptions, config: Record<string, unknown>) {
  // Cross-app target BFFs must not reuse the source application's gateway
  // runtime token.  In service-client-policy mode the target obtains a fresh
  // token from its own exact `<app>.runtime` credential policy.
  let staticToken = ''
  if (options.serviceTokenSourceBinding !== 'service-client-policy') {
    staticToken = tenantRuntimeToken(event, options.appCode, config)
  }
  if (options.requireStaticRuntimeToken) {
    // Tenant Gateway already minted and HMAC-bound this short-lived token for
    // the current tenant/deployment. Reusing it avoids a second Platform lookup
    // during the nested service-token exchange; Runtime still verifies the
    // EdDSA signature and exact bootstrap claims before issuing any token.
    const forwardedPlatformBootstrap = isPlatformRuntimeBootstrapToken(staticToken)
      ? staticToken
      : ''
    const refreshedPlatformBootstrap = forwardedPlatformBootstrap
      ? ''
      : await requestPlatformRuntimeBootstrapToken(event, config)
    const bootstrapToken = forwardedPlatformBootstrap || refreshedPlatformBootstrap || staticToken
    if (!bootstrapToken) {
      throw createError({
        statusCode: 503,
        message: 'An enrolled Tenant Runtime bootstrap token is required for this operation.'
      })
    }

    // The Platform bootstrap credential is deliberately restricted to the
    // service-token issuer. It must never be presented directly to client
    // credential consumption, enrollment, or other Console Runtime routes.
    if (options.scope === 'console:service-token:issue') return bootstrapToken
    if (!isPlatformRuntimeBootstrapToken(bootstrapToken)) return bootstrapToken

    const audience = tenantRuntimeAudience(event, config)
    return await requestServiceAccessToken({
      audience,
      scope: tenantRuntimeTokenScope(audience, options.scope),
      sourceBinding: options.serviceTokenSourceBinding,
      event
    })
  }
  if (staticToken && !isPlatformRuntimeBootstrapToken(staticToken)) return staticToken
  const audience = tenantRuntimeAudience(event, config)
  return await requestServiceAccessToken({
    audience,
    scope: tenantRuntimeTokenScope(audience, options.scope),
    sourceBinding: options.serviceTokenSourceBinding,
    event
  })
}

function currentSubjectUid(event: H3Event) {
  return stringValue(verifiedUserConsoleAuth(event)?.uid)
}

function verifiedUserConsoleAuth(event: H3Event) {
  const consoleAuth = event.context.consoleAuth as TenantRuntimeActorAuth | undefined
  if (!consoleAuth?.authenticated || consoleAuth.subjectType === 'service') return null
  return consoleAuth
}

function splitCodes(value: unknown): string[] {
  if (Array.isArray(value)) return value.flatMap(item => splitCodes(item))
  return String(value || '')
    .split(/[,\s;]+/)
    .map(item => item.trim())
    .filter(Boolean)
}

function uniqueCodes(values: string[]) {
  return Array.from(new Set(values))
}

function currentSubjectDeptCodes(event: H3Event) {
  const consoleAuth = verifiedUserConsoleAuth(event)
  const values: string[] = []
  if (consoleAuth) {
    values.push(...splitCodes(consoleAuth.deptCodes))
    values.push(...splitCodes(consoleAuth.deptCode))
    values.push(...splitCodes(consoleAuth.claims?.dept_codes))
    values.push(...splitCodes(consoleAuth.claims?.dept_code))
  }
  return uniqueCodes(values)
}

function base64Url(bytes: ArrayBuffer) {
  let binary = ''
  for (const byte of new Uint8Array(bytes)) {
    binary += String.fromCharCode(byte)
  }
  return btoa(binary)
    .replace(/\+/g, '-')
    .replace(/\//g, '_')
    .replace(/=+$/g, '')
}

async function signActorDelegation(input: {
  token: string
  method: TenantRuntimeMethod
  requestTarget: string
  actorUid: string
  deptCodes: string[]
  signedAt: string
  purpose?: string
}) {
  const encoder = new TextEncoder()
  const key = await crypto.subtle.importKey(
    'raw',
    encoder.encode(input.token),
    { name: 'HMAC', hash: 'SHA-256' },
    false,
    ['sign']
  )
  const values = [
    input.method,
    input.requestTarget,
    input.actorUid,
    input.deptCodes.join(','),
    input.signedAt
  ]
  if (input.purpose) values.push(input.purpose)
  const payload = values.join('\n')
  const signature = await crypto.subtle.sign('HMAC', key, encoder.encode(payload))
  return base64Url(signature)
}

type ServiceCommandEnvelope = {
  operationId: string
  targetApp: string
  operationCode: string
  requiredCapability: string
  idempotencyKey: string
  commandSchemaVersion: string
  commandSha256: string
  command?: Record<string, unknown>
}

export type SignedServiceCommandEnvelope = ServiceCommandEnvelope

function serviceCommandEnvelope(body: unknown): ServiceCommandEnvelope | null {
  if (!body || typeof body !== 'object' || Array.isArray(body)) return null
  const raw = (body as Record<string, unknown>).serviceCommand
  if (!raw || typeof raw !== 'object' || Array.isArray(raw)) return null
  const value = raw as Record<string, unknown>
  const command = value.command && typeof value.command === 'object' && !Array.isArray(value.command)
    ? value.command as Record<string, unknown>
    : undefined
  const envelope = {
    operationId: stringValue(value.operationId),
    targetApp: stringValue(value.targetApp),
    operationCode: stringValue(value.operationCode),
    requiredCapability: stringValue(value.requiredCapability),
    idempotencyKey: stringValue(value.idempotencyKey),
    commandSchemaVersion: stringValue(value.commandSchemaVersion),
    commandSha256: stringValue(value.commandSha256),
    command
  }
  if (Object.entries(envelope).some(([key, item]) => key !== 'command' && !item)) {
    throw createError({ statusCode: 400, message: 'Service command envelope is incomplete.' })
  }
  return envelope
}

async function signHmac(token: string, payload: string) {
  const encoder = new TextEncoder()
  const key = await crypto.subtle.importKey(
    'raw',
    encoder.encode(token),
    { name: 'HMAC', hash: 'SHA-256' },
    false,
    ['sign']
  )
  return base64Url(await crypto.subtle.sign('HMAC', key, encoder.encode(payload)))
}

function base64UrlBytes(value: string) {
  const normalized = String(value || '').trim().replace(/-/g, '+').replace(/_/g, '/')
  if (!normalized || !/^[A-Za-z0-9+/]+={0,2}$/u.test(normalized)) return new Uint8Array()
  const padded = normalized + '='.repeat((4 - normalized.length % 4) % 4)
  try {
    const binary = atob(padded)
    return Uint8Array.from(binary, character => character.charCodeAt(0))
  } catch {
    return new Uint8Array()
  }
}

function serviceCommandCanonical(input: {
  method: TenantRuntimeMethod
  requestTarget: string
  tenantCode: string
  sourceDeploymentCode: string
  targetDeploymentCode: string
  sourceApp: string
  sourceClientId: string
  targetApp: string
  envelope: ServiceCommandEnvelope
  requestId: string
  signedAt: string
}) {
  return [
    input.method,
    input.requestTarget,
    input.tenantCode,
    input.sourceDeploymentCode,
    input.targetDeploymentCode,
    input.sourceApp,
    input.sourceClientId,
    input.targetApp,
    input.envelope.operationId,
    input.envelope.operationCode,
    input.envelope.requiredCapability,
    input.envelope.idempotencyKey,
    input.envelope.commandSchemaVersion,
    input.envelope.commandSha256,
    input.requestId,
    input.signedAt
  ].join('\n')
}

export async function hashServiceCommandPayload(payload: unknown) {
  const encoded = new TextEncoder().encode(JSON.stringify(payload))
  const digest = await crypto.subtle.digest('SHA-256', encoded)
  return [...new Uint8Array(digest)].map(byte => byte.toString(16).padStart(2, '0')).join('')
}

export async function buildServiceCommandRuntimeHeaders(input: {
  token: string
  method: TenantRuntimeMethod
  requestTarget: string
  requestId: string
  tenantCode: string
  sourceDeploymentCode: string
  targetDeploymentCode: string
  sourceApp: string
  sourceClientId: string
  targetApp: string
  envelope: ServiceCommandEnvelope
  signedAt?: string
}) {
  const signedAt = input.signedAt || String(Date.now())
  if (
    !input.token
    || !input.tenantCode
    || !input.sourceDeploymentCode
    || !input.targetDeploymentCode
    || !input.sourceApp
    || !input.sourceClientId
    || !input.targetApp
    || input.sourceApp === input.targetApp
    || input.envelope.targetApp !== input.targetApp
  ) {
    throw createError({ statusCode: 403, message: 'Trusted service command context is incomplete.' })
  }
  const canonical = serviceCommandCanonical({ ...input, signedAt })
  return {
    'x-hzy-service-command-tenant': input.tenantCode,
    'x-hzy-service-command-source-deployment': input.sourceDeploymentCode,
    'x-hzy-service-command-target-deployment': input.targetDeploymentCode,
    'x-hzy-service-command-source-app': input.sourceApp,
    'x-hzy-service-command-source-client': input.sourceClientId,
    'x-hzy-service-command-target-app': input.targetApp,
    'x-hzy-service-command-operation-id': input.envelope.operationId,
    'x-hzy-service-command-operation-code': input.envelope.operationCode,
    'x-hzy-service-command-capability': input.envelope.requiredCapability,
    'x-hzy-service-command-idempotency-key': input.envelope.idempotencyKey,
    'x-hzy-service-command-schema-version': input.envelope.commandSchemaVersion,
    'x-hzy-service-command-sha256': input.envelope.commandSha256,
    'x-hzy-service-command-signed-at': signedAt,
    'x-hzy-service-command-signature': await signHmac(input.token, canonical)
  }
}

/**
 * Verifies the same short-lived HMAC envelope built above before a target BFF
 * turns a source-provided actor into a runtime service-command actor. The
 * target must provide values from the verified inbound token/context, never
 * from the body, and must separately bind commandSha256 to its fixed command.
 */
export async function verifyServiceCommandRuntimeHeaders(input: {
  token: string
  method: TenantRuntimeMethod
  requestTarget: string
  requestId: string
  tenantCode: string
  sourceDeploymentCode: string
  targetDeploymentCode: string
  sourceApp: string
  sourceClientId: string
  targetApp: string
  envelope: ServiceCommandEnvelope
  readHeader: (name: string) => unknown
  now?: number
}) {
  const headers = {
    tenantCode: stringValue(input.readHeader('x-hzy-service-command-tenant')),
    sourceDeploymentCode: stringValue(input.readHeader('x-hzy-service-command-source-deployment')),
    targetDeploymentCode: stringValue(input.readHeader('x-hzy-service-command-target-deployment')),
    sourceApp: stringValue(input.readHeader('x-hzy-service-command-source-app')),
    sourceClientId: stringValue(input.readHeader('x-hzy-service-command-source-client')),
    targetApp: stringValue(input.readHeader('x-hzy-service-command-target-app')),
    operationId: stringValue(input.readHeader('x-hzy-service-command-operation-id')),
    operationCode: stringValue(input.readHeader('x-hzy-service-command-operation-code')),
    requiredCapability: stringValue(input.readHeader('x-hzy-service-command-capability')),
    idempotencyKey: stringValue(input.readHeader('x-hzy-service-command-idempotency-key')),
    commandSchemaVersion: stringValue(input.readHeader('x-hzy-service-command-schema-version')),
    commandSha256: stringValue(input.readHeader('x-hzy-service-command-sha256')),
    signedAt: stringValue(input.readHeader('x-hzy-service-command-signed-at')),
    signature: stringValue(input.readHeader('x-hzy-service-command-signature'))
  }
  const expected = {
    tenantCode: input.tenantCode,
    sourceDeploymentCode: input.sourceDeploymentCode,
    targetDeploymentCode: input.targetDeploymentCode,
    sourceApp: input.sourceApp,
    sourceClientId: input.sourceClientId,
    targetApp: input.targetApp,
    operationId: input.envelope.operationId,
    operationCode: input.envelope.operationCode,
    requiredCapability: input.envelope.requiredCapability,
    idempotencyKey: input.envelope.idempotencyKey,
    commandSchemaVersion: input.envelope.commandSchemaVersion,
    commandSha256: input.envelope.commandSha256
  }
  if (
    !input.token || !input.requestTarget || !input.requestId
    || Object.values(headers).some(value => !value)
    || Object.entries(expected).some(([key, value]) => headers[key as keyof typeof headers] !== value)
  ) {
    throw createError({ statusCode: 403, message: 'Trusted service command signature context is invalid.' })
  }
  const signedAt = Number(headers.signedAt)
  const now = input.now ?? Date.now()
  if (!Number.isSafeInteger(signedAt) || signedAt > now + 5_000 || now - signedAt > 60_000) {
    throw createError({ statusCode: 403, message: 'Trusted service command signature is expired.' })
  }
  const signature = base64UrlBytes(headers.signature)
  if (signature.length === 0) {
    throw createError({ statusCode: 403, message: 'Trusted service command signature is invalid.' })
  }
  const encoder = new TextEncoder()
  const key = await crypto.subtle.importKey('raw', encoder.encode(input.token), { name: 'HMAC', hash: 'SHA-256' }, false, ['verify'])
  const valid = await crypto.subtle.verify('HMAC', key, signature, encoder.encode(serviceCommandCanonical({
    method: input.method,
    requestTarget: input.requestTarget,
    tenantCode: input.tenantCode,
    sourceDeploymentCode: input.sourceDeploymentCode,
    targetDeploymentCode: input.targetDeploymentCode,
    sourceApp: input.sourceApp,
    sourceClientId: input.sourceClientId,
    targetApp: input.targetApp,
    envelope: input.envelope,
    requestId: input.requestId,
    signedAt: headers.signedAt
  })))
  if (!valid) {
    throw createError({ statusCode: 403, message: 'Trusted service command signature is invalid.' })
  }
}

