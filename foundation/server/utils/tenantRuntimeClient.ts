function safeJwtMetadata(token: string) {
  try {
    const [encodedHeader, encodedPayload] = token.split('.')
    if (!encodedHeader || !encodedPayload) return { format: 'opaque' }
    const header = JSON.parse(Buffer.from(encodedHeader, 'base64url').toString('utf8')) as Record<string, unknown>
    const payload = JSON.parse(Buffer.from(encodedPayload, 'base64url').toString('utf8')) as Record<string, unknown>
    const hzy = payload.hzy && typeof payload.hzy === 'object' && !Array.isArray(payload.hzy)
      ? payload.hzy as Record<string, unknown>
      : {}
    return {
      format: 'jwt',
      kid: stringValue(header.kid),
      alg: stringValue(header.alg),
      issuer: stringValue(payload.iss),
      audience: Array.isArray(payload.aud) ? payload.aud.map(stringValue) : stringValue(payload.aud),
      tokenUse: stringValue(payload.token_use),
      tenant: stringValue(payload.tenant || payload.tenant_code || payload.tenantCode),
      deployment: stringValue(payload.deployment || payload.deployment_code || payload.deploymentCode),
      appCode: stringValue(payload.appCode || payload.app_code || hzy.appCode),
      scope: Array.isArray(payload.scope) ? payload.scope.map(stringValue) : stringValue(payload.scope),
      issuedAt: Number(payload.iat || 0),
      expiresAt: Number(payload.exp || 0),
      observedAt: Math.floor(Date.now() / 1000)
    }
  } catch {
    return { format: 'unparseable' }
  }
}

function safeUpstreamResponseMetadata(error: unknown) {
  const response = (error as {
    response?: {
      headers?: Headers | Record<string, unknown>
    }
  })?.response
  const headers = response?.headers
  const headerValue = (name: string) => {
    if (!headers) return ''
    if (typeof (headers as Headers).get === 'function') {
      return stringValue((headers as Headers).get(name))
    }
    const record = headers as Record<string, unknown>
    return stringValue(record[name] || record[name.toLowerCase()])
  }
  const data = (error as { data?: unknown })?.data
  const responseText = typeof data === 'string'
    ? data.replace(/<[^>]*>/gu, ' ').replace(/\s+/gu, ' ').trim()
    : ''
  const title = typeof data === 'string'
    ? stringValue(data.match(/<title[^>]*>([^<]{1,160})<\/title>/iu)?.[1])
    : ''
  const cloudflareErrorCode = responseText.match(/\b(?:error\s+code|cloudflare)\D{0,24}(\d{3,4})\b/iu)?.[1] || ''
  return {
    server: headerValue('server'),
    contentType: headerValue('content-type'),
    cfRay: headerValue('cf-ray'),
    title,
    cloudflareErrorCode,
    responseSummary: responseText.slice(0, 240),
    responseShape: Array.isArray(data)
      ? 'array'
      : data === null
        ? 'null'
        : typeof data
  }
}

export function isPlatformRuntimeBootstrapToken(token: string) {
  const metadata = safeJwtMetadata(token) as Record<string, unknown>
  return metadata.format === 'jwt'
    && metadata.tokenUse === 'platform_runtime_bootstrap'
}

function serviceAuthScopes(auth: TenantRuntimeActorAuth) {
  const scopes = new Set<string>()
  const rawScopes = auth.claims?.scope
  const authScopes = auth.scopes
  for (const item of [
    ...(Array.isArray(rawScopes) ? rawScopes : String(rawScopes || '').split(/\s+/)),
    ...(Array.isArray(authScopes) ? authScopes : String(authScopes || '').split(/\s+/))
  ]) {
    const scope = stringValue(item)
    if (scope) scopes.add(scope)
  }
  return scopes
}

function trustedNotificationDetailActor(input: {
  event: H3Event
  path: string
  options: TenantRuntimeCallOptions
  tenant: string
  deployment: string
}) {
  const delegation = input.options.notificationDetailActor
  if (!delegation) return ''

  const auth = input.event.context.consoleAuth as TenantRuntimeActorAuth | undefined
  const sourceApp = stringValue(auth?.appCode || auth?.clientCode).replace(/\.runtime$/u, '')
  const expectedScope = `${input.options.appCode}:notification-details:authorize`
  const expectedPath = `/v1/${input.options.appCode}/notification-details/authorize`
  const uid = stringValue(delegation.uid)
  const tenantId = stringValue(delegation.tenantId)
  const deploymentId = stringValue(delegation.deploymentId)
  const hasControlCharacter = [...uid].some((character) => {
    const code = character.codePointAt(0) || 0
    return code < 32 || code === 127
  })

  if (
    !auth?.authenticated
    || auth.subjectType !== 'service'
    || auth.tokenUse !== 'service'
    || sourceApp !== 'console'
    || !serviceAuthScopes(auth).has(expectedScope)
    || String(input.options.method || 'GET').toUpperCase() !== 'POST'
    || input.path !== expectedPath
    || !uid
    || uid.length > 191
    || hasControlCharacter
    || !tenantId
    || tenantId !== stringValue(auth.tenant)
    || tenantId !== input.tenant
    || !deploymentId
    || deploymentId !== stringValue(auth.deployment)
    || deploymentId !== input.deployment
  ) {
    throw createError({ statusCode: 403, message: 'Trusted notification detail actor delegation is invalid.' })
  }
  return uid
}

function trustedServiceCommandActor(input: {
  event: H3Event
  options: TenantRuntimeCallOptions
  envelope: Record<string, unknown> | null
}) {
  const uid = stringValue(input.options.serviceCommandActor?.uid)
  if (!uid || !input.envelope) return ''
  const auth = input.event.context.consoleAuth as TenantRuntimeActorAuth | undefined
  const sourceApp = stringValue(auth?.appCode || auth?.clientCode).replace(/\.runtime$/u, '')
  const command = input.envelope.command as Record<string, unknown> | undefined
  const capability = stringValue(input.envelope.requiredCapability)
  if (
    !auth?.authenticated
    || auth.subjectType !== 'service'
    || auth.tokenUse !== 'service'
    || !sourceApp
    || !capability
    || !serviceAuthScopes(auth).has(capability)
    || stringValue(input.envelope.targetApp) !== input.options.appCode
    || stringValue(command?.actorUid) !== uid
    || uid.length > 191
    || [...uid].some(character => (character.codePointAt(0) || 0) < 32 || (character.codePointAt(0) || 0) === 127)
  ) {
    throw createError({ statusCode: 403, message: 'Trusted service-command actor delegation is invalid.' })
  }
  return uid
}

function validDelegatedUid(value: string) {
  return Boolean(value)
    && value.length <= 191
    && ![...value].some((character) => {
      const code = character.codePointAt(0) || 0
      return code < 32 || code === 127
    })
}

function trustedWorkflowProxyActor(input: {
  event: H3Event
  path: string
  options: TenantRuntimeCallOptions
  tenant: string
  deployment: string
}) {
  const delegation = input.options.workflowProxyActor
  if (!delegation) return ''

  const auth = input.event.context.consoleAuth as TenantRuntimeActorAuth | undefined
  const sourceApp = stringValue(auth?.appCode || auth?.clientCode).replace(/\.runtime$/u, '')
  const declaredApp = stringValue(getHeader(input.event, 'x-hzy-request-app-code'))
  const uid = stringValue(delegation.uid)
  const sourceTenant = stringValue(auth?.tenant)
  const sourceDeployment = stringValue(auth?.deployment)
  const usesServiceClientPolicy = input.options.serviceTokenSourceBinding === 'service-client-policy'

  if (
    !auth?.authenticated
    || auth.subjectType !== 'service'
    || auth.tokenUse !== 'service'
    || input.options.appCode !== 'workflow'
    || !input.path.startsWith('/v1/workflow/')
    || !serviceAuthScopes(auth).has('workflow:proxy')
    || !sourceApp
    || declaredApp !== sourceApp
    || !validDelegatedUid(uid)
    || !sourceTenant
    || sourceTenant !== input.tenant
    || !sourceDeployment
    // The legacy trusted-gateway path signs for the same deployment.  A
    // cross-app Workflow proxy deliberately retains the source app deployment
    // in its verified caller token while the separately issued target runtime
    // token binds `input.deployment` to Workflow's exact client policy.
    || (!usesServiceClientPolicy && sourceDeployment !== input.deployment)
  ) {
    throw createError({ statusCode: 403, message: 'Trusted Workflow proxy actor delegation is invalid.' })
  }
  return uid
}

