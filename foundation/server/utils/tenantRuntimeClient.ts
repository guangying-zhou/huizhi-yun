function isTrustedTenantGatewayRequest(event: H3Event, config: Record<string, unknown>) {
  if (stringValue(getHeader(event, 'x-hzy-gateway')) !== 'tenant-gateway') return false
  const expectedToken = tenantGatewayInternalToken(event, config)
  if (!expectedToken) return false
  return constantTimeEquals(stringValue(getHeader(event, 'x-hzy-gateway-token')), expectedToken)
}

async function requestPlatformRuntimeBootstrapToken(event: H3Event, config: Record<string, unknown>) {
  if (!isTrustedTenantGatewayRequest(event, config)) return ''

  const tenantCode = stringValue(getHeader(event, 'x-hzy-tenant'))
  const deploymentCode = stringValue(getHeader(event, 'x-hzy-deployment'))
  const environment = stringValue(getHeader(event, 'x-hzy-environment'))
  const appCode = stringValue(getHeader(event, 'x-hzy-app-code'))
  const internalToken = tenantGatewayInternalToken(event, config)
  const baseUrl = platformBaseUrl(event, config).replace(/\/+$/u, '')
  // Only a Console gateway request may mint a fresh Platform bootstrap token.
  // A trusted business-app request to Console's token endpoint instead carries
  // the already-issued Console Runtime bootstrap token from its original
  // tenant-gateway context; let resolveBearerToken validate and use that token.
  if (appCode !== 'console') return ''
  if (!tenantCode || !deploymentCode || !environment || !internalToken || !baseUrl) {
    throw createError({
      statusCode: 503,
      message: 'Trusted Tenant Gateway Runtime bootstrap context is incomplete.'
    })
  }

  const cacheKey = [baseUrl, tenantCode, deploymentCode, environment, appCode].join('|')
  const cached = platformRuntimeBootstrapCache.get(cacheKey)
  if (cached && cached.expiresAt > Date.now() + 10_000) return cached.token

  let response: PlatformRuntimeBootstrapResponse
  try {
    response = await fetchExternal<PlatformRuntimeBootstrapResponse>(
      `${baseUrl}/api/platform/internal/tenant-gateway/runtime-bootstrap-token`,
      {
        method: 'POST',
        headers: {
          'authorization': `Bearer ${internalToken}`,
          'content-type': 'application/json',
          'user-agent': workerServiceUserAgent,
          'x-hzy-internal-principal': 'console-runtime-bootstrap'
        },
        body: { tenantCode, environment, appCode },
        timeout: 10000
      }
    )
  } catch {
    throw createError({
      statusCode: 503,
      message: 'Platform Runtime bootstrap token is unavailable.'
    })
  }

  const token = stringValue(response?.data?.token)
  const expiresAt = Date.parse(stringValue(response?.data?.expiresAt))
  const metadata = safeJwtMetadata(token) as Record<string, unknown>
  if (
    !token
    || !Number.isFinite(expiresAt)
    || expiresAt <= Date.now() + 10_000
    || metadata.tokenUse !== 'platform_runtime_bootstrap'
    || metadata.tenant !== tenantCode
    || metadata.deployment !== deploymentCode
    || metadata.appCode !== appCode
    || stringValue(response?.data?.tenantCode) !== tenantCode
    || stringValue(response?.data?.deploymentCode) !== deploymentCode
    || stringValue(response?.data?.appCode) !== appCode
  ) {
    throw createError({
      statusCode: 503,
      message: 'Platform Runtime bootstrap token binding is invalid.'
    })
  }

  platformRuntimeBootstrapCache.set(cacheKey, { token, expiresAt })
  return token
}

function tenantGatewayHeader(event: H3Event, names: string[], config: Record<string, unknown>) {
  if (!isTrustedTenantGatewayRequest(event, config)) return ''
  for (const name of names) {
    const value = stringValue(getHeader(event, name))
    if (value) return value
  }
  return ''
}

