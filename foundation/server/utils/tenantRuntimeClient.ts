export async function maybeCallTenantRuntime<T>(
  event: H3Event,
  path: string,
  options: TenantRuntimeCallOptions
): Promise<TenantRuntimeSkipped | TenantRuntimeHandled<T>> {
  const config = useRuntimeConfig() as unknown as Record<string, unknown>
  const endpoint = tenantRuntimeEndpoint(event, options.appCode, config)
  if (!shouldCallTenantRuntime(config, options.appCode, endpoint)) {
    return { handled: false }
  }

  const url = new URL(path, endpoint.endsWith('/') ? endpoint : `${endpoint}/`)
  appendQuery(url, options.query || getQuery(event))
  const method = normalizeMethod(options.method)
  const token = await measureRequestStage(event, 'runtime_token', () => resolveBearerToken(event, options, config))
  const tokenMetadata = safeJwtMetadata(token) as Record<string, unknown>
  const envelope = serviceCommandEnvelope(options.body)
  const requestId = stringValue(getHeader(event, 'x-request-id') || getHeader(event, 'x-correlation-id'))
    || (envelope ? crypto.randomUUID() : '')
  const idempotencyKey = stringValue(options.idempotencyKey || getHeader(event, 'idempotency-key'))
  const gatewayTenant = optionalHeader(event, config, [
    'hzy.tenantRuntime.tenant',
    'tenantRuntime.tenant',
    'hzy.dataRuntime.tenant',
    'dataRuntime.tenant'
  ], [
    'HZY_TENANT_RUNTIME_TENANT',
    'HZY_DATA_RUNTIME_TENANT'
  ], ['x-hzy-tenant'])
  const gatewayDeployment = optionalHeader(event, config, [
    'hzy.tenantRuntime.deployment',
    'tenantRuntime.deployment',
    'hzy.dataRuntime.deployment',
    'dataRuntime.deployment'
  ], [
    'HZY_TENANT_RUNTIME_DEPLOYMENT',
    'HZY_DATA_RUNTIME_DEPLOYMENT'
  ], ['x-hzy-deployment'])
  const usesServiceClientPolicy = options.serviceTokenSourceBinding === 'service-client-policy'
  const tenant = usesServiceClientPolicy ? stringValue(tokenMetadata.tenant) : gatewayTenant
  const deployment = usesServiceClientPolicy ? stringValue(tokenMetadata.deployment) : gatewayDeployment
  if (usesServiceClientPolicy && (!tenant || !deployment)) {
    throw createError({
      statusCode: 503,
      message: 'Service client token is missing its tenant/runtime deployment policy binding.'
    })
  }
  const delegatedSubjectUid = trustedNotificationDetailActor({
    event,
    path,
    options,
    tenant,
    deployment
  })
  const serviceCommandSubjectUid = trustedServiceCommandActor({ event, options, envelope })
  const workflowProxySubjectUid = trustedWorkflowProxyActor({
    event,
    path,
    options,
    tenant,
    deployment
  })
  const subjectUid = delegatedSubjectUid || serviceCommandSubjectUid || workflowProxySubjectUid || currentSubjectUid(event)
  const subjectDeptCodes = delegatedSubjectUid ? [] : currentSubjectDeptCodes(event)
  const actorSignedAt = subjectUid ? String(Date.now()) : ''
  const actorSignature = subjectUid
    ? await signActorDelegation({
        token,
        method,
        requestTarget: `${url.pathname}${url.search}`,
        actorUid: subjectUid,
        deptCodes: subjectDeptCodes,
        signedAt: actorSignedAt,
        purpose: delegatedSubjectUid ? 'notification-detail-authorization' : serviceCommandSubjectUid ? 'service-command' : undefined
      })
    : ''
  let serviceCommandHeaders: Record<string, string> = {}
  if (envelope) {
    const incoming = event.context.consoleAuth as TenantRuntimeActorAuth | undefined
    const sourceApp = stringValue(incoming?.appCode || incoming?.clientCode).replace(/\.runtime$/u, '')
    const sourceClientId = stringValue(incoming?.clientCode || incoming?.appCode)
    const sourceTenant = stringValue(incoming?.tenant)
    const sourceDeployment = stringValue(incoming?.deployment)
    if (
      !incoming?.authenticated
      || incoming.subjectType !== 'service'
      || incoming.tokenUse !== 'service'
      || !sourceApp
      || !sourceClientId
      || sourceTenant !== tenant
    ) {
      throw createError({ statusCode: 403, message: 'Verified source service identity is required for service commands.' })
    }
    serviceCommandHeaders = await buildServiceCommandRuntimeHeaders({
      token,
      method,
      requestTarget: `${url.pathname}${url.search}`,
      requestId,
      tenantCode: sourceTenant,
      sourceDeploymentCode: sourceDeployment,
      targetDeploymentCode: deployment,
      sourceApp,
      sourceClientId,
      targetApp: options.appCode,
      envelope
    })
  }

  try {
    const data = await measureRequestStage(event, 'runtime_http', () => fetchExternal<T>(url.toString(), {
      method,
      headers: {
        'authorization': `Bearer ${token}`,
        'user-agent': workerServiceUserAgent,
        ...(method === 'GET' ? {} : { 'content-type': 'application/json' }),
        ...(requestId ? { 'x-request-id': requestId } : {}),
        ...(idempotencyKey ? { 'idempotency-key': idempotencyKey } : {}),
        ...(subjectUid ? { 'x-hzy-actor-uid': subjectUid } : {}),
        ...(subjectDeptCodes[0] ? { 'x-hzy-actor-dept-code': subjectDeptCodes[0] } : {}),
        ...(subjectDeptCodes.length > 0 ? { 'x-hzy-actor-dept-codes': subjectDeptCodes.join(',') } : {}),
        ...(actorSignedAt ? { 'x-hzy-actor-signed-at': actorSignedAt } : {}),
        ...(actorSignature ? { 'x-hzy-actor-signature': actorSignature } : {}),
        ...(delegatedSubjectUid ? { 'x-hzy-actor-purpose': 'notification-detail-authorization' } : serviceCommandSubjectUid ? { 'x-hzy-actor-purpose': 'service-command' } : {}),
        ...(tenant ? { 'x-hzy-tenant': tenant } : {}),
        ...(deployment ? { 'x-hzy-deployment': deployment } : {}),
        ...serviceCommandHeaders
      },
      ...(method === 'GET' ? {} : { body: options.body ?? {} }),
      timeout: options.timeoutMs || 10000
    }))
    return { handled: true, data }
  } catch (error: unknown) {
    const fetchError = error as {
      status?: number
      statusCode?: number
      statusMessage?: string
      data?: TenantRuntimeErrorEnvelope
    }
    const runtimeError = tenantRuntimeErrorData(
      fetchError,
      error instanceof Error ? error.message : String(error)
    )
    if (runtimeError.upstreamStatus >= 400) {
      const logMessage = runtimeError.upstreamStatus === 401 || runtimeError.upstreamStatus === 403
        ? '[tenantRuntimeClient] tenant runtime rejected authenticated request'
        : '[tenantRuntimeClient] tenant runtime request failed'
      console.warn(logMessage, {
        appCode: options.appCode,
        path: url.pathname,
        code: runtimeError.code,
        upstreamStatus: runtimeError.upstreamStatus,
        upstream: safeUpstreamResponseMetadata(error),
        token: safeJwtMetadata(token)
      })
    }
    throw createError({
      statusCode: runtimeError.statusCode,
      statusMessage: runtimeError.statusCode === 503 ? 'Tenant Runtime unavailable' : fetchError.statusMessage,
      message: runtimeError.message,
      data: {
        code: runtimeError.code,
        message: runtimeError.message,
        upstreamStatus: runtimeError.upstreamStatus
      }
    })
  }
}

export async function maybeCallCurrentAppTenantRuntime<T>(
  event: H3Event,
  options: {
    appCode: string
    scope: string
    pathPrefix?: string
  }
): Promise<TenantRuntimeSkipped | TenantRuntimeHandled<T>> {
  const pathname = getRequestURL(event).pathname
  const marker = options.pathPrefix || '/api/v1'
  const markerIndex = pathname.indexOf(marker)
  if (markerIndex < 0) return { handled: false }

  const suffix = pathname.slice(markerIndex + marker.length)
  const path = `/v1/${options.appCode}${suffix}`
  const method = normalizeMethod(event.node.req.method)
  const body = method === 'GET' ? undefined : await readRequestBodyCompat(event)
  return maybeCallTenantRuntime<T>(event, path, {
    appCode: options.appCode,
    scope: options.scope,
    method,
    body
  })
}
