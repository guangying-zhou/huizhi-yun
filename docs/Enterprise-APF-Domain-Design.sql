-- ============================================================================
-- Enterprise 统一业务库：Altoc / People / Finance 三域新 schema（设计稿 DDL）
-- 配套文档：docs/Enterprise-APF-Domain-Design.md（以文档为准，本文件是可审阅的草案）
--
-- 状态：设计稿，未执行、未进入 domaininstall manifest。首批（B1）= Finance 参数/账户 +
--       Altoc 客户/报价/合同主链；B2/B3/B4 块为后批，列出以固定命名与关系。
-- 约定：
--   * 物理名 = 逻辑名，域前缀 altoc_ / people_ / finance_；不生成兼容视图。
--   * SharedPhysicalNames（integration_operation 等 4 项）按域前缀建表，经 Resolved.Table 访问。
--   * 跨域只存稳定业务键（uid / dept_code / project_code / *_code），不建跨域 FK；域内允许 FK。
--   * 金额 DECIMAL(18,2)，比例 DECIMAL(8,4)，币种 CHAR(3) NOT NULL DEFAULT 'CNY'。
--   * 乐观锁列统一 row_version INT UNSIGNED NOT NULL DEFAULT 1；审计列 created_by/updated_by/
--     created_at/updated_at(DATETIME(3))；需要软删的表有 deleted_at。
--   * 不含任何 legacy_* / 迁移映射列：历史数据不迁移。客户主数据只预留 source_system/external_ref。
--   * utf8mb4 / utf8mb4_unicode_ci，与 Aims/Assets 统一库一致。
-- ============================================================================

