CREATE TABLE finance_subject (
    id              BIGINT UNSIGNED PRIMARY KEY AUTO_INCREMENT,
    code            VARCHAR(50)  NOT NULL COMMENT '科目编码（小企业会计准则 4 位码或自定义）',
    name            VARCHAR(100) NOT NULL,
    subject_type    VARCHAR(30)  NOT NULL COMMENT 'asset/liability/equity/cost/profit_loss',
    parent_id       BIGINT UNSIGNED DEFAULT NULL,
    sort_no         INT NOT NULL DEFAULT 0,
    status          VARCHAR(20)  NOT NULL DEFAULT 'active' COMMENT 'active/inactive',
    remark          VARCHAR(500) DEFAULT NULL,
    row_version     INT UNSIGNED NOT NULL DEFAULT 1,
    created_by      VARCHAR(64) DEFAULT NULL,
    updated_by      VARCHAR(64) DEFAULT NULL,
    created_at      DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at      DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    UNIQUE KEY uk_finance_subject_code (code),
    KEY idx_finance_subject_type (subject_type, status, sort_no),
    KEY idx_finance_subject_parent (parent_id),
    CONSTRAINT fk_finance_subject_parent FOREIGN KEY (parent_id) REFERENCES finance_subject(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='财务科目/经营分类';

