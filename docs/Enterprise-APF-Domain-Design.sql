CREATE TABLE finance_people_cost_parameter (
    id                          BIGINT UNSIGNED PRIMARY KEY AUTO_INCREMENT,
    code                        VARCHAR(50)  NOT NULL,
    name                        VARCHAR(100) NOT NULL,
    effective_from              DATE NOT NULL,
    effective_to                DATE DEFAULT NULL,
    base_salary                 DECIMAL(18,2) NOT NULL DEFAULT 0.00 COMMENT '基本工资基数',
    welfare_cost_rate           DECIMAL(10,4) NOT NULL DEFAULT 0.0000 COMMENT '福利成本费率',
    management_allocation_rate  DECIMAL(10,4) NOT NULL DEFAULT 0.0000 COMMENT '管理分摊系数',
    resource_allocation_cost    DECIMAL(18,2) NOT NULL DEFAULT 0.00 COMMENT '固定资源分摊成本',
    currency_code               CHAR(3) NOT NULL DEFAULT 'CNY',
    status                      VARCHAR(20) NOT NULL DEFAULT 'active' COMMENT 'active/inactive',
    remark                      VARCHAR(500) DEFAULT NULL,
    row_version                 INT UNSIGNED NOT NULL DEFAULT 1,
    created_by                  VARCHAR(64) DEFAULT NULL,
    updated_by                  VARCHAR(64) DEFAULT NULL,
    created_at                  DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at                  DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    UNIQUE KEY uk_finance_people_cost_parameter_code (code),
    KEY idx_finance_people_cost_parameter_effective (status, effective_from, effective_to),
    CONSTRAINT ck_finance_people_cost_parameter_range CHECK (effective_to IS NULL OR effective_to >= effective_from),
    CONSTRAINT ck_finance_people_cost_parameter_nonneg CHECK (base_salary >= 0 AND welfare_cost_rate >= 0 AND management_allocation_rate >= 0 AND resource_allocation_cost >= 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='人力成本核算参数（People 成本快照与 Finance 项目人力成本共用的参数事实源；同一时点只允许一条 active 生效，由领域写入校验）';

